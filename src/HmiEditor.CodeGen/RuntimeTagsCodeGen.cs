using System.Text;
using HmiEditor.Core.Models;
using HmiEditor.Core.Services;

namespace HmiEditor.CodeGen;

/// <summary>
/// 运行时标签表代码生成器 —— 将绑定引擎的标签表生成为设备 C 代码。
///
/// 生成内容:
///   - 变量索引枚举 (tag_index_t): 每个标签一个稳定索引
///   - 标签元数据数组: 地址/方向/换算系数
///   - 抽象读写接口 var_read/var_write (由设备实现层提供)
///   - 标签名称 → 索引映射表 (运行时诊断/调试用)
///
/// 设计要点:
///   - 索引基于引擎构建顺序，稳定可预测
///   - 换算系数 (scale/offset) 直接嵌入代码, 设备层读写原始值,
///     应用层 get_tag_value 负责 eng = raw*scale + offset
///   - 写方向保护: READ_ONLY 标签的写操作在 C 侧拒绝
/// </summary>
public class RuntimeTagsCodeGen
{
    /// <summary>
    /// 数据类型 → **原始值**范围（含端点）。<c>Float</c>/未知类型无界 ⇒ <c>hasRange=false</c>
    /// （宁松勿误拒：量程默认口径只挡"类型装不下"的值）。
    /// </summary>
    private static (bool HasRange, string Min, string Max) RawRangeOf(string? dataType) =>
        (dataType ?? "").Trim().ToLowerInvariant() switch
        {
            // ⚠ 必须是**带小数点的字面量**（生成代码里有守卫：`1f` 不是合法 C 浮点常量）
            "bool" => (true, "0.0", "1.0"),
            "int16" or "short" or "i16" => (true, "-32768.0", "32767.0"),
            "uint16" or "ushort" or "u16" or "word" => (true, "0.0", "65535.0"),
            "int32" or "int" or "i32" or "dint" => (true, "-2147483648.0", "2147483647.0"),
            "uint32" or "u32" or "udint" or "dword" => (true, "0.0", "4294967295.0"),
            _ => (false, "0.0", "0.0"),
        };

    /// <summary>生成标签表 C 代码块（含头注释）。</summary>
    public string Generate(IReadOnlyList<RuntimeTag> tags)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// ── Runtime Tag Table ──");
        // ⚠ 阶段 318：同一 TU 里若**已经包含** tags.h（主机测试就是这么编的：tags.h 先、
        //   tags.c 后），本文件的枚举/结构体/访问器会与头里那套**重声明**，编译直接不过。
        //   旧夹具的 tags.c 只定义表、不声明类型，所以没这个问题；当前生成器两处都发。
        //   最稳的修法：整个 .c 以"头文件未被包含"为前提 —— 头在，则本文件不参与（头已提供同样的东西）。
        sb.AppendLine("#ifndef HMI_GENERATED_TAGS_H");
        sb.AppendLine($"// Total: {tags.Count} tags (auto-generated by HmiEditor)");
        sb.AppendLine();

        if (tags.Count == 0)
        {
            sb.AppendLine("// No bound variables.");
            sb.AppendLine("#endif /* HMI_GENERATED_TAGS_H */");
        return sb.ToString();
        }

        sb.AppendLine("typedef enum {");
        for (int i = 0; i < tags.Count; i++)
        {
            sb.AppendLine($"    TAG_{Sanitize(tags[i].VariableId)} = {i},");
        }
        sb.AppendLine("    TAG_COUNT");
        sb.AppendLine("} tag_index_t;");
        sb.AppendLine();

        // 标签元数据表
        sb.AppendLine("typedef struct {");
        sb.AppendLine("    const char* name;");
        sb.AppendLine("    const char* address;");
        sb.AppendLine("    uint8_t read_only;   // 1 = 只读 (写操作拒绝)");
        sb.AppendLine("    float scale;");
        sb.AppendLine("    float offset;");
        // ── 阶段 288：远程写的**值域口径**（默认 = 数据类型的可表示范围；Float 无界 ⇒ has_range = 0）──
        // 追加在**尾部**：宿主 hmi_tags_adopt 存指针不拷贝，两侧同一份生成头 ⇒ 安全。
        sb.AppendLine("    uint8_t has_range;   /* 1 = min/max 有效（默认由数据类型推导；Float ⇒ 0 = 不限） */");
        sb.AppendLine("    float min_value;     /* 原始值下界（含） */");
        sb.AppendLine("    float max_value;     /* 原始值上界（含） */");
        sb.AppendLine("} tag_meta_t;");
        sb.AppendLine();

        sb.AppendLine("static const tag_meta_t TAG_TABLE[TAG_COUNT] = {");
        foreach (var tag in tags)
        {
            var readOnly = tag.Direction == BindingDirection.ReadOnly ? 1 : 0;
            var scale = FormatFloat(tag.Scale);
            var offset = FormatFloat(tag.Offset);
            var (hasRange1, min1, max1) = RawRangeOf(tag.DataType);
            sb.AppendLine($"    {{\"{Escape(tag.VariableId)}\", \"{Escape(tag.Address)}\", {readOnly}, {scale}f, {offset}f, {(hasRange1 ? 1 : 0)}, {min1}f, {max1}f}},");
        }
        sb.AppendLine("};");
        sb.AppendLine();

        // 抽象接口（设备实现层提供）
        sb.AppendLine("/* 设备层接口 —— 由通讯实现提供 (modbus_tcp.c / modbus_rtu.c 等) */");
        sb.AppendLine("extern float var_raw_read(int index);");
        sb.AppendLine("extern void var_raw_write(int index, float raw);");
        sb.AppendLine();

        // 应用层工具函数
        sb.AppendLine("/* 应用层读写 —— 自动应用 scale/offset 换算与只读保护 */");
        sb.AppendLine("static inline float get_tag_value(tag_index_t idx) {");
        sb.AppendLine("    if (idx < 0 || idx >= TAG_COUNT) return 0.0f;");
        sb.AppendLine("    const tag_meta_t* t = &TAG_TABLE[idx];");
        sb.AppendLine("    return var_raw_read(idx) * t->scale + t->offset;");
        sb.AppendLine("}");
        sb.AppendLine();

        sb.AppendLine("static inline uint8_t set_tag_value(tag_index_t idx, float eng) {");
        sb.AppendLine("    if (idx < 0 || idx >= TAG_COUNT) return 0;");
        sb.AppendLine("    const tag_meta_t* t = &TAG_TABLE[idx];");
        sb.AppendLine("    if (t->read_only) return 0;    /* 只读保护 */");
        sb.AppendLine("    float raw = (t->scale != 0.0f) ? (eng - t->offset) / t->scale : eng;");
        sb.AppendLine("    var_raw_write(idx, raw);");
        sb.AppendLine("    return 1;");
        sb.AppendLine("}");
        sb.AppendLine();

        // 名称 → 索引查找（运行时诊断）
        sb.AppendLine("/* 按名称查找标签索引, 未找到返回 -1 */");
        sb.AppendLine("static inline int tag_index_by_name(const char* name) {");
        sb.AppendLine("    for (int i = 0; i < TAG_COUNT; i++) {");
        sb.AppendLine("        if (strcmp(TAG_TABLE[i].name, name) == 0) return i;");
        sb.AppendLine("    }");
        sb.AppendLine("    return -1;");
        sb.AppendLine("}");

        sb.AppendLine("#endif /* HMI_GENERATED_TAGS_H */");
        return sb.ToString();
    }

    /// <summary>生成 C 标识符安全的标签常量名（CodeGenerator 共用）。</summary>
    public static string SanitizeIdentifierPublic(string id)
    {
        var sb = new StringBuilder(id.Length);
        foreach (var c in id)
        {
            if (char.IsLetterOrDigit(c))
                sb.Append(c);
            else
                sb.Append('_');
        }
        return sb.ToString();
    }

    /// <summary>
    /// 生成标签表契约头文件（ABI V3，.so 自包含）：
    ///   - HMI_UI_TAG_META / HMI_UI_TAG_BINDINGS 内嵌为 static const 表 ——
    ///     .so 不再 extern 依赖宿主 TAG_TABLE/TAG_BINDINGS 符号，换工程热更新不失配；
    ///   - get_tag_value/set_tag_value 直接使用内嵌元数据（scale/offset/只读保护）；
    ///   - var_raw_read/write 仍由宿主变量表提供（设备层 I/O）；
    ///   - 宿主 hmi_ui_load 时经 hmi_ui_get_api().get_tags/get_tag_bindings 采纳
    ///     本表驱动轮询组/MQTT 主题，与 .so 枚举序一致。
    /// </summary>
    public string GenerateHeader(IReadOnlyList<RuntimeTag> tags)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/*");
        sb.AppendLine(" * tags.h — 标签表契约（由 zhishu-HMI 编辑器导出，ABI V3 .so 自包含）");
        sb.AppendLine(" *");
        sb.AppendLine(" * tag_meta_t   标签元数据（name/address/read_only/scale/offset）");
        sb.AppendLine(" * tag_binding_t 通信绑定（driver/addr/unit/dtype/poll_ms）");
        sb.AppendLine(" * HMI_UI_TAG_META/HMI_UI_TAG_BINDINGS 内嵌于本头（static const），");
        sb.AppendLine(" * 宿主 hmi_runtime 经 get_tags/get_tag_bindings 采纳（变量表/轮询组/MQTT 主题）。");
        sb.AppendLine(" */");
        sb.AppendLine("#ifndef HMI_GENERATED_TAGS_H");
        sb.AppendLine("#define HMI_GENERATED_TAGS_H");
        sb.AppendLine();
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine("#include <string.h>");
        sb.AppendLine();

        if (tags.Count == 0)
        {
            sb.AppendLine("/* 工程未配置绑定变量。 */");
            sb.AppendLine("typedef enum { TAG_COUNT = 0 } tag_index_t;");
        }
        else
        {
            sb.AppendLine("typedef enum {");
            for (var i = 0; i < tags.Count; i++)
                sb.AppendLine($"    TAG_{Sanitize(tags[i].VariableId)} = {i},");
            sb.AppendLine("    TAG_COUNT");
            sb.AppendLine("} tag_index_t;");
        }
        sb.AppendLine();

        sb.AppendLine("typedef struct {");
        sb.AppendLine("    const char* name;");
        sb.AppendLine("    const char* address;");
        sb.AppendLine("    uint8_t read_only;   /* 1 = 只读（写操作拒绝） */");
        sb.AppendLine("    float scale;");
        sb.AppendLine("    float offset;");
        // ── 阶段 288：远程写的**值域口径**（默认 = 数据类型的可表示范围；Float 无界 ⇒ has_range = 0）──
        // 追加在**尾部**：宿主 hmi_tags_adopt 存指针不拷贝，两侧同一份生成头 ⇒ 安全。
        sb.AppendLine("    uint8_t has_range;   /* 1 = min/max 有效（默认由数据类型推导；Float ⇒ 0 = 不限） */");
        sb.AppendLine("    float min_value;     /* 原始值下界（含） */");
        sb.AppendLine("    float max_value;     /* 原始值上界（含） */");
        sb.AppendLine("} tag_meta_t;");
        sb.AppendLine();

        sb.AppendLine("typedef struct {");
        sb.AppendLine("    const char* driver;   /* \"modbus-rtu\" / \"modbus-tcp\" / \"mqtt\" / \"local\" */");
        sb.AppendLine("    const char* addr;     /* 地址串（\"40001\"/\"00001\"/\"h:0\"/\"3:0\"...） */");
        sb.AppendLine("    uint8_t     unit;     /* Modbus 从站号 */");
        sb.AppendLine("    const char* dtype;    /* Bool/U16/I16/U32/I32/Float */");
        sb.AppendLine("    uint16_t    poll_ms;  /* 轮询周期（0=不轮询） */");
        sb.AppendLine("} tag_binding_t;");
        sb.AppendLine();

        // ── 内嵌元数据表（.so 自包含） ──
        sb.AppendLine("/* ── 标签元数据（.so 内嵌；宿主经 get_tags 采纳） ── */");
        sb.AppendLine("static const tag_meta_t HMI_UI_TAG_META[TAG_COUNT > 0 ? TAG_COUNT : 1] = {");
        foreach (var t in tags)
        {
            var readOnly = t.Direction == BindingDirection.ReadOnly ? 1 : 0;
            var (hasRange2, min2, max2) = RawRangeOf(t.DataType);
            sb.AppendLine($"    {{ \"{Escape(t.VariableId)}\", \"{Escape(t.Address)}\", {readOnly}, {F(t.Scale)}, {F(t.Offset)}, {(hasRange2 ? 1 : 0)}, {min2}f, {max2}f }},");
        }
        if (tags.Count == 0)
            sb.AppendLine("    { \"\", \"\", 0, 1.0f, 0.0f, 0, 0.0f, 0.0f },");
        sb.AppendLine("};");
        sb.AppendLine();

        sb.AppendLine("/* ── 通信绑定（.so 内嵌；宿主经 get_tag_bindings 采纳） ── */");
        sb.AppendLine("static const tag_binding_t HMI_UI_TAG_BINDINGS[TAG_COUNT > 0 ? TAG_COUNT : 1] = {");
        foreach (var t in tags)
        {
            var driver = !string.IsNullOrEmpty(t.DriverId) ? t.DriverId : "local";
            var dtype = MapDtype(t.DataType);
            // addr 必须是纯 Modbus 地址（RawAddress，如 "40001"）——固件 hmi_tag_parse_addr
            // 的 "%d:%d" 分支是「功能码:偏移」语义，站号拼进地址会把站号当功能码、
            // 完整地址当偏移（越界/错区），轮询组请求错误。从站路由走 unit：
            // 子设备变量用 SlaveAddress，无子设备回退 1（连接默认从站见 generated_comm.h）。
            var addr = !string.IsNullOrEmpty(t.RawAddress) ? t.RawAddress : StripSlavePrefix(t.Address);
            var unit = t.SlaveAddress > 0 ? t.SlaveAddress : 1;
            sb.AppendLine($"    {{ \"{Escape(driver)}\", \"{Escape(addr)}\", {unit}, \"{dtype}\", 100 }},");
        }
        if (tags.Count == 0)
            sb.AppendLine("    { \"local\", \"\", 0, \"U16\", 0 },");
        sb.AppendLine("};");
        sb.AppendLine();

        // 设备层接口（firmware app/runtime/variable_table.c 实现）
        sb.AppendLine("/* 设备层接口（firmware app/runtime/variable_table.c 实现） */");
        sb.AppendLine("extern float var_raw_read(int index);");
        sb.AppendLine("extern void  var_raw_write(int index, float raw);");
        sb.AppendLine();

        // 应用层读写 —— 自动应用 scale/offset 换算与只读保护（用内嵌元数据，不再依赖宿主表）
        sb.AppendLine("/* 应用层读写 —— 自动应用 scale/offset 换算与只读保护（内嵌元数据） */");
        sb.AppendLine("static inline float get_tag_value(tag_index_t idx)");
        sb.AppendLine("{");
        sb.AppendLine("    if (idx < 0 || idx >= TAG_COUNT) return 0.0f;");
        sb.AppendLine("    const tag_meta_t* t = &HMI_UI_TAG_META[idx];");
        sb.AppendLine("    return var_raw_read((int)idx) * t->scale + t->offset;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("static inline uint8_t set_tag_value(tag_index_t idx, float eng)");
        sb.AppendLine("{");
        sb.AppendLine("    if (idx < 0 || idx >= TAG_COUNT) return 0;");
        sb.AppendLine("    const tag_meta_t* t = &HMI_UI_TAG_META[idx];");
        sb.AppendLine("    if (t->read_only) return 0;    /* 只读保护 */");
        sb.AppendLine("    float raw = (t->scale != 0.0f) ? (eng - t->offset) / t->scale : eng;");
        sb.AppendLine("    var_raw_write((int)idx, raw);");
        sb.AppendLine("    return 1;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("#endif /* HMI_GENERATED_TAGS_H */");
        return sb.ToString();
    }

    /// <summary>编辑器数据类型 → 设备 dtype 串（Bool/U16/I16/U32/I32/Float）。</summary>
    private static string MapDtype(string dataType) => dataType switch
    {
        "Bool" or "Boolean" => "Bool",
        "Int16" or "Short" or "UInt16" or "U16" => "U16",
        "Int32" or "Integer" or "Int" => "I32",
        "UInt32" or "U32" => "U32",
        "Float" or "Single" or "Double" => "Float",
        "I16" => "I16",
        "I32" => "I32",
        _ => "U16"
    };

    private static string Escape(string s) => (s ?? "")
        .Replace("\\", "\\\\")
        .Replace("\"", "\\\"")
        .Replace("\n", "\\n")
        .Replace("\r", "\\r")
        .Replace("\t", "\\t");

    /// <summary>剥离地址的「站号:」前缀（防御：RawAddress 缺失时兜底）。仅当冒号前为纯数字时剥离。</summary>
    private static string StripSlavePrefix(string address)
    {
        if (string.IsNullOrEmpty(address)) return address ?? "";
        var idx = address.IndexOf(':');
        if (idx <= 0 || idx == address.Length - 1) return address;
        var prefix = address.AsSpan(0, idx);
        var isDigits = true;
        foreach (var c in prefix)
        {
            if (c < '0' || c > '9') { isDigits = false; break; }
        }
        return isDigits ? address[(idx + 1)..] : address;
    }

    /// <summary>
    /// C 浮点字面量（不带 f 后缀）：必须用 InvariantCulture，否则逗号小数区会产出 "0,5f"；
    /// 且必须用足够精度，旧实现 "0.###" 会把 0.00001 变成 "0" → 拼成非法的 "0f"。
    /// </summary>
    private static string F(double v) => FloatLiteral(v) + "f";

    private static string FloatLiteral(double v)
    {
        if (double.IsNaN(v) || double.IsInfinity(v)) return "0.0";
        var s = v.ToString("G10", System.Globalization.CultureInfo.InvariantCulture);
        if (!s.Contains('.') && !s.Contains('e') && !s.Contains('E'))
            s += ".0";
        return s;
    }

    private static string Sanitize(string id) => SanitizeIdentifierPublic(id);

    /// <summary>浮点格式化（C 字面量，不含 f 后缀）：InvariantCulture + 保证合法且不丢精度。</summary>
    private static string FormatFloat(double value) => FloatLiteral(value);
}
