    // ── 构建系统生成（消费 ExportConfig.GenerateBuildSystem）──

    /// <summary>构建系统生成产物（文件名 + 内容）。</summary>
    public sealed class BuildArtifact
    {
        public string FileName { get; }
        public string Content { get; }
        public BuildArtifact(string fileName, string content)
        {
            FileName = fileName;
            Content = content;
        }
    }

    /// <summary>
    /// 按 ExportConfig.GenerateBuildSystem 生成构建系统配置文件。
    /// 返回 null 表示不生成（BuildSystem.None）。
    /// </summary>
    public BuildArtifact? GenerateBuildSystem(HmiProject project)
    {
        return project.ExportConfig.GenerateBuildSystem switch
        {
            BuildSystem.CMake => new BuildArtifact("CMakeLists.txt", GenerateCMake(project)),
            BuildSystem.Makefile => new BuildArtifact("Makefile", GenerateMakefile(project)),
            BuildSystem.PlatformIO => new BuildArtifact("platformio.ini", GeneratePlatformIni(project)),
            _ => null
        };
    }

    private static string GenerateCMake(HmiProject project)
    {
        var appName = SafeAppName(project.Name);
        var optFlag = OptimizationFlag(project.ExportConfig.CodeGenOptimization) + DebugSymbolFlag(project);
        var isCpp = project.ExportConfig.TargetLanguage == TargetLanguage.Cpp;
        var lang = isCpp ? "CXX" : "C";
        var stdVar = isCpp ? "CMAKE_CXX_STANDARD" : "CMAKE_C_STANDARD";
        var stdVal = isCpp ? "17" : "99";
        var flagsVar = isCpp ? "CMAKE_CXX_FLAGS" : "CMAKE_C_FLAGS";
        var src = isCpp ? "generated_hmi.cpp" : "generated_hmi.c";
        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by HmiEditor — CMake build for LVGL HMI");
        sb.AppendLine("cmake_minimum_required(VERSION 3.10)");
        sb.AppendLine($"project({appName} {lang})");
        sb.AppendLine();
        sb.AppendLine($"set({stdVar} {stdVal})");
        sb.AppendLine($"set({flagsVar} \"${{{flagsVar}}} {optFlag} -Wall\")");
        sb.AppendLine();
        sb.AppendLine("# LVGL 路径（按实际位置调整）");
        sb.AppendLine("# set(LVGL_DIR ${CMAKE_SOURCE_DIR}/lvgl)");
        sb.AppendLine("# include(${LVGL_DIR}/lvgl.cmake)");
        sb.AppendLine();
        sb.AppendLine("# 自动生成的 HMI 源文件");
        sb.AppendLine("set(HMI_SOURCES");
        sb.AppendLine($"    {src}");
        sb.AppendLine(")");
        sb.AppendLine();
        sb.AppendLine("add_executable(${PROJECT_NAME} ${HMI_SOURCES})");
        // 运行时模式宏（SecurityConfig.OperationMode → HMI_OPERATION_MODE 条件编译）
        sb.AppendLine($"# 运行时模式（0=Designer, 1=Operator, 2=Maintenance, 3=ReadOnly）");
        sb.AppendLine($"target_compile_definitions(${{PROJECT_NAME}} PRIVATE {OperationModeDefine(project)} {TamperDetectionDefine(project)})");
        sb.AppendLine("# target_include_directories(${PROJECT_NAME} PRIVATE ${LVGL_DIR})");
        sb.AppendLine("# target_link_libraries(${PROJECT_NAME} lvgl)");
        return sb.ToString();
    }

    private static string GenerateMakefile(HmiProject project)
    {
        var appName = SafeAppName(project.Name);
        var optFlag = OptimizationFlag(project.ExportConfig.CodeGenOptimization) + DebugSymbolFlag(project);
        var isCpp = project.ExportConfig.TargetLanguage == TargetLanguage.Cpp;
        var compiler = isCpp ? "CXX" : "CC";
        var compilerBin = isCpp ? "g++" : "gcc";
        var stdFlag = isCpp ? "-std=gnu++17" : "-std=gnu99";
        var flagsVar = isCpp ? "CXXFLAGS" : "CFLAGS";
        var src = isCpp ? "generated_hmi.cpp" : "generated_hmi.c";
        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by HmiEditor — Makefile for LVGL HMI");
        sb.AppendLine($"{compiler} ?= {compilerBin}");
        // 运行时模式宏（SecurityConfig.OperationMode → HMI_OPERATION_MODE 条件编译）
        sb.AppendLine($"{flagsVar} ?= {stdFlag} {optFlag} -Wall -I. -Ilvgl -D{OperationModeDefine(project)} -D{TamperDetectionDefine(project)}");
        sb.AppendLine("LDFLAGS ?= -lm");
        sb.AppendLine();
        sb.AppendLine($"HMI_SOURCES = {src}");
        sb.AppendLine();
        sb.AppendLine($"{appName}: $(HMI_SOURCES)");
        sb.AppendLine($"\t$({compiler}) $({flagsVar}) -o {appName} $(HMI_SOURCES) $(LDFLAGS)");
        sb.AppendLine();
        sb.AppendLine("clean:");
        sb.AppendLine($"\trm -f {appName}");
        return sb.ToString();
    }

    private static string GeneratePlatformIni(HmiProject project)
    {
        var appName = SafeAppName(project.Name);
        var isCpp = project.ExportConfig.TargetLanguage == TargetLanguage.Cpp;
        // 运行时模式宏（SecurityConfig.OperationMode → HMI_OPERATION_MODE 条件编译）
        var buildFlags = (isCpp ? "-Ilvgl -std=c++17" : "-Ilvgl")
            + $" -D{OperationModeDefine(project)} -D{TamperDetectionDefine(project)}"
            + DebugSymbolFlag(project);
        var sb = new StringBuilder();
        sb.AppendLine("; Auto-generated by HmiEditor — PlatformIO config for LVGL HMI");
        sb.AppendLine("[platformio]");
        sb.AppendLine("default_envs = native");
        sb.AppendLine();
        sb.AppendLine("[env:native]");
        sb.AppendLine("platform = native");
        sb.AppendLine("framework =");
        sb.AppendLine($"build_flags = {buildFlags}");
        // 包含 src/ 下所有 C/C++ 源，避免排除用户添加的辅助源文件
        sb.AppendLine("src_filter = +<*.c> +<*.cpp>");
        sb.AppendLine($"target_name = {appName}");
        return sb.ToString();
    }

    /// <summary>项目名转合法可执行文件名；中文/非法字符回退为 hmi_app。</summary>
    private static string SafeAppName(string? projectName)
    {
        var sanitized = string.IsNullOrEmpty(projectName) ? "" : CIdentifier.ForControlSymbol(projectName);
        if (!IsValidCIdentifier(sanitized)) return "hmi_app";
        return sanitized;
    }

    /// <summary>判断是否为合法 C 标识符（首字符字母/下划线，后续字母/数字/下划线）。</summary>
    private static bool IsValidCIdentifier(string s)
    {
        if (s.Length == 0) return false;
        if (!IsIdentStart(s[0])) return false;
        foreach (var c in s)
            if (!IsIdentChar(c)) return false;
        return true;

        static bool IsIdentStart(char c) => c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
        static bool IsIdentChar(char c) => IsIdentStart(c) || (c >= '0' && c <= '9');
    }

    /// <summary>CodeGenOptimization → 编译器优化标志。</summary>
    private static string OptimizationFlag(CodeGenOptimization opt) => opt switch
    {
        CodeGenOptimization.Size => "-Os",
        CodeGenOptimization.Speed => "-O2",
        CodeGenOptimization.Readability => "-O0 -g",
        _ => "-Os"
    };

    /// <summary>
    /// <c>ExportConfig.GenerateDebugSymbols</c> → 编译器调试符号标志。
    /// <para>
    /// 关闭（默认）时返回 <b>空串</b>，因此三份构建配置的产物与不含该选项时逐字节相同 ——
    /// 这是刻意的：老工程重导出不应因为加了这个选项而改变产物。
    /// </para>
    /// <para>
    /// 与 <see cref="OptimizationFlag"/> 的 <c>Readability → "-O0 -g"</c> 不冲突：
    /// 两者叠加时最多出现两个 <c>-g</c>，编译器按幂等处理。
    /// </para>
    /// </summary>
    private static string DebugSymbolFlag(HmiProject project) =>
        project.ExportConfig.GenerateDebugSymbols ? " -g" : "";

    /// <summary>
    /// 生成 OperationMode 宏定义（如 "HMI_OPERATION_MODE=1"，不含 -D 前缀）。
    /// 固件代码可通过 #if HMI_OPERATION_MODE == 1 等条件编译按运行模式裁剪行为。
    /// 值对齐 <see cref="OperationMode"/> 枚举：0=Designer, 1=Operator, 2=Maintenance, 3=ReadOnly。
    /// </summary>
    private static string OperationModeDefine(HmiProject project)
        => $"HMI_OPERATION_MODE={(int)project.SecurityConfig.OperationMode}";

    /// <summary>
    /// 生成 EnableTamperDetection 宏定义（如 "HMI_TAMPER_DETECTION=1"，不含 -D 前缀）。
    /// 1=启用防篡改检测，0=禁用。
    ///
    /// <para><b>当前状态：下发了但零消费。</b>固件全树没有任何 <c>#if HMI_TAMPER_DETECTION</c>
    /// （grep 确认只出现在生成器与本文件/测试里），所以勾选它<b>不会</b>改变设备行为。
    /// 本注释此前写的是「固件代码可通过 <c>#if HMI_TAMPER_DETECTION</c> 条件编译启用/禁用
    /// Flash 扇区 CRC 校验」—— 那是一句没验证过的行为描述，已删除：把没验证过的行为写进注释，
    /// 后来人会当成事实用（阶段 7 已因同一原因修过一处同类注释）。</para>
    ///
    /// <para>要闭环得先定三件事，属**新功能**而非补缺口：① 防的是什么篡改、校验对象是谁
    /// （<c>/rom</c> 是只读 squashfs，改不动）；② 基准校验值在生成期还是运行期产生、存在哪；
    /// ③ 检出异常之后怎么办（拒绝启动 / 只记审计 / 进保护模式）。</para>
    /// </summary>
    private static string TamperDetectionDefine(HmiProject project)
        => $"HMI_TAMPER_DETECTION={(project.SecurityConfig.EnableTamperDetection ? 1 : 0)}";
}
