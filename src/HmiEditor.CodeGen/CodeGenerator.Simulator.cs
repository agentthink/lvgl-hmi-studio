/// <summary>
/// CodeGenerator 分部 —— 模拟器（PC/SDL 导出）模块发射 —— GenerateSimulatorModule。
/// </summary>
public partial class CodeGenerator
{
    /// <summary>
    /// 生成 HMI 模块代码（主题/标签/脚本/屏幕/动画/报警/趋势），不含 main()。
    /// 供 PC 模拟器导出使用 —— 模拟器提供自己的 main.c 入口（LVGL + SDL2 窗口）。
    /// </summary>
    public string GenerateSimulatorModule(HmiProject project, AssetLibrary? assetLibrary = null)
    {
        var sb = new StringBuilder();
        _soMode = false;

        // ExportConfig.IncludeComments —— 控制标注性注释开闭
        _includeComments = project.ExportConfig.IncludeComments;

        // 构建运行时标签表 —— 收集所有屏幕控件的变量绑定
        var bindingEngine = new RuntimeBindingEngine(project);
        bindingEngine.BuildRuntimeTags();
        var tags = bindingEngine.Tags;

        sb.AppendLine("// =========================================");
        sb.AppendLine("// Auto-generated by HmiEditor — DO NOT EDIT");
        sb.AppendLine($"// LVGL: {project.LvglVersion}");
        sb.AppendLine($"// Target: {project.HardwareTargetId ?? "generic"}");
        sb.AppendLine($"// Theme: {EscapeComment(project.Theme.Name)}");
        sb.AppendLine($"// Runtime tags: {tags.Count}");
        sb.AppendLine($"// Generator: {GeneratorStamp}");
        sb.AppendLine("// =========================================");
        sb.AppendLine();

        // ExportConfig.IncludeLgplDisclaimer —— LVGL 要求生成代码声明 LGPL 许可
        if (project.ExportConfig.IncludeLgplDisclaimer)
        {
            sb.AppendLine("/*");
            sb.AppendLine(" * SPDX-License-Identifier: LGPL-2.1-or-later");
            sb.AppendLine(" * Auto-generated by HmiEditor. Links against LVGL (MIT license).");
            sb.AppendLine(" * Modifications will be overwritten on re-export.");
            sb.AppendLine(" */");
            sb.AppendLine();
        }

        sb.AppendLine("#include \"lvgl.h\"");
        sb.AppendLine("#include <stdio.h>");
        sb.AppendLine("#include <string.h>");
        sb.AppendLine();
        // 权限模型（HMI_PERM_* / 角色表）：动作回调的权限门引用的宏来自它。
        // 用 __has_include 而不是无条件 include —— 设计模式下根本不发射门，缺这份头也能编译
        // （设备端 hmi_actions.h 有同样的回退，两侧一致）。
        sb.AppendLine("#if defined(__has_include)");
        sb.AppendLine("#  if __has_include(\"generated_security.h\")");
        sb.AppendLine("#    include \"generated_security.h\"");
        sb.AppendLine("#  endif");
        sb.AppendLine("#endif");
        sb.AppendLine();

        // 生成图片和字体资源声明（从参数传入的 AssetLibrary）
        // 宽松判定 Type 是否为图片: 枚举 AssetType.Image 之外, 兼容 "image/Image/IMAGE"
        // 等字符串化的存储值（某些版本/历史工程中可能出现），避免可用图片被误判为不可用
        // 导致后续控件引用 IMG_PATH_xxx 时出现"未声明标识符"编译错误。
        static bool IsImageAsset(AssetItem a)
        {
            if (a.Type == AssetType.Image) return true;
            // 兜底: 反序列化时若 Type 字段解析失败, 枚举通常会保持默认值或 0,
            // 再结合 FilePath 扩展名做二次确认, 尽量覆盖历史数据。
            var ext = Path.GetExtension(a.FilePath ?? "")
                .TrimStart('.')
                .ToLowerInvariant();
            return ext is "png" or "jpg" or "jpeg" or "bmp" or "gif" or "webp";
        }
        static bool IsFontAsset(AssetItem a)
        {
            if (a.Type == AssetType.Font) return true;
            var ext = Path.GetExtension(a.FilePath ?? "")
                .TrimStart('.')
                .ToLowerInvariant();
            return ext is "ttf" or "ttc" or "otf" or "woff" or "woff2";
        }

        var imageAssets = assetLibrary?.Assets.Where(IsImageAsset).ToList() ?? new List<AssetItem>();
        var fontAssets = assetLibrary?.Assets.Where(IsFontAsset).ToList() ?? new List<AssetItem>();
        // 资源符号表：整批资源只算一次（净化 / 文件名 / 变尺寸字体），后续一律查表。
        // 同一符号若在多处独立重算，任一处漂移都会让产物内部自相矛盾
        // （generated_hmi.c 声明 font_X、generated_fonts.c 定义 font_Y）。详见 CResourceSymbols。
        var symbols = CResourceSymbols.Create(imageAssets, fontAssets, project);
        var availableImageIds = symbols.Images.Select(i => i.Fragment).ToHashSet();
        var availableFontIds = symbols.Fonts.Select(f => f.Fragment).ToHashSet();

        if (symbols.Images.Count > 0 || symbols.Fonts.Count > 0)
        {
            sb.AppendLine("// 资源声明（图片/字体）");
            foreach (var img in symbols.Images)
            {
                sb.AppendLine($"/* 图片资产: {EscapeComment(img.Id)} (运行时绝对路径由 SIM_ASSET_DIR 注入) */");
                sb.AppendLine(CResourceDeclarations.ImagePathMacroDefine(img.Fragment, img.FileName));
                sb.AppendLine(CResourceDeclarations.ImageExtern(img.Fragment));
            }
            foreach (var font in symbols.Fonts)
                sb.AppendLine(CResourceDeclarations.FontExtern(font.Fragment));
            // 控件自定义字号字体外部声明（由 generated_fonts.c / 固件字体模块提供）
            foreach (var variant in symbols.FontVariants)
                sb.AppendLine(CResourceDeclarations.FontVariantExtern(variant.FontFragment, variant.Size));
            sb.AppendLine();
        }

        // 指针/游标对象文件级声明（Slider knob 三角 / Bar 游标+三角）：
        // create_screen_* 赋值、sim_refresh_bindings 更新位置，跨函数需 static 全局。
        sb.Append(GeneratePointerDeclarations(project));
        // Slider/Bar 值变化回调（触摸拖动/代码设值时三角/游标跟随 knob 移动）
        sb.Append(AppendPointerValueCallbacks(project));

        // 运行时动作 API —— 由固件提供 (screen_manager.c / hmi_actions.c)
        // 前向声明使生成代码自包含可编译；hmi_run_script 由脚本分发表内联定义
        // ExportConfig.TargetLanguage=Cpp：固件 C API 用 extern "C" 包裹，保证 C++ 编译器正确链接
        var isCpp = project.ExportConfig.TargetLanguage == TargetLanguage.Cpp;
        if (isCpp) sb.AppendLine("extern \"C\" {");
        sb.AppendLine("/* 运行时动作 API —— 由固件提供 (screen_manager.c / hmi_actions.c) */");
        sb.AppendLine("extern int  hmi_screen_switch(const char* name);");
        sb.AppendLine("extern void hmi_show_alarms(void);");
        sb.AppendLine("extern void hmi_show_trends(void);");
        sb.AppendLine("extern void hmi_login(void);");
        // 凭据提交（登录屏上的按钮）—— 宿主定义：固件 app/runtime/hmi_actions.c、
        // 模拟器 exports/main.c。这条声明同时也是 SimulatorLinkContractTests 的输入：
        // 它会反推导出工程必须提供定义，漏了就红（而不是等 cmake 链接期才炸）。
        sb.AppendLine("extern int  hmi_login_submit(const char* user, const char* password);");
        sb.AppendLine("extern void hmi_logout(void);");
        // 权限门（仅 SecurityConfig.OperationMode != Designer 时生成器会发射调用）
        sb.AppendLine("extern int  hmi_require_permission(unsigned int bits);");
        if (isCpp) sb.AppendLine("}  /* extern \"C\" — 固件 C API */");
        sb.AppendLine();

        // 生成主题样式初始化（传入 assetLibrary 以获取字体资源）
        sb.AppendLine(GenerateThemeCode(project.Theme, assetLibrary));

        // 生成运行时标签表 —— 绑定引擎 → 设备 C 变量表
        sb.AppendLine(new RuntimeTagsCodeGen().Generate(tags));

        // 生成脚本分发表 —— script_id → C 函数指针派发 + hmi_run_script 实现
        sb.AppendLine(new ScriptDispatchCodeGen().Generate(project.Scripts));

        // 创建 Faceplate 展开器 —— 用于在代码生成前展开 Faceplate 实例
        var expander = new FaceplateExpander(project.Templates);

        // 图层引用：被引用的公共页面作为背景图层嵌入，不再提供独立全屏入口
        var referencedLayerIds = ScreenLayerRefs.CollectReferencedLayerIds(project);
        EmitLayerValidationComments(sb, project);

        // 为每个 Screen 生成创建函数（_inner 工厂 + 独立屏幕顶层包装）
        foreach (var screen in project.Screens)
        {
            sb.AppendLine(GenerateScreenCode(screen, project.Theme, expander, tags, project, availableImageIds, availableFontIds));
            if (!referencedLayerIds.Contains(screen.Id))
                sb.AppendLine(GenerateScreenTopLevelWrapper(screen));
        }

        // 绑定模拟刷新函数（模拟器用）：无设备层时正弦波驱动绑定显示控件，
        // 与设计器预览模式动态效果对齐。无绑定时不生成。
        sb.AppendLine(GenerateSimRefreshBindings(tags, project));

        // 生成动画代码
        sb.AppendLine(GenerateAnimationCode(project.AnimationConfigs));

        // 报警引擎与趋势图：仅在项目配置了对应内容时生成（空配置返回占位注释）。
        // 变量报警（Variable.Alarms）聚合成"变量报警"分组一并生成。
        sb.AppendLine(GenerateAlarmCode(MergeVariableAlarmGroups(project)));
        sb.AppendLine(GenerateTrendCode(project.TrendConfigs, project.DataLogConfigs));

        return LvglApiCompatChecker.Process(sb.ToString(), project.LvglVersion);
    }
}
