using System.Text;
using HmiEditor.Core.Models.Scripting;

namespace HmiEditor.CodeGen;

/// <summary>
/// 脚本分发表代码生成器 —— 将项目脚本集合生成为 C 分发表 + 派发 API。
///
/// 生成内容:
///   - HMI_WEAK 可移植宏（GCC/Clang 用 __attribute__((weak))，否则空）
///   - 每个脚本的 weak stub 入口 script_&lt;id&gt;(void)（用户/固件可提供同名 strong 实现覆盖）
///   - HMI_SCRIPTS[] 分发表: script_id → 函数指针
///   - hmi_run_script(const char* script_id) 实现: 线性查找并调用，未找到返回 -1
///
/// 设计要点:
///   - weak stub 保证导出代码立即可链接，无需固件为每个脚本单独提供实现
///   - 用户/固件可在另一翻译单元提供同名 strong 实现覆盖桩
///   - 空脚本集仍生成 hmi_run_script 桩（返回 -1），保证调用方始终可链接
///   - 标识符净化复用 RuntimeTagsCodeGen.SanitizeIdentifierPublic
/// </summary>
public class ScriptDispatchCodeGen
{
    /// <summary>生成脚本分发表 C 代码块（含头注释）。</summary>
    public string Generate(IReadOnlyList<HmiScript> scripts)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// ── Script Dispatch Table ──");
        sb.AppendLine($"// Total: {scripts.Count} scripts (auto-generated by HmiEditor)");
        sb.AppendLine();

        // 可移植 weak 宏
        sb.AppendLine("#ifndef HMI_WEAK");
        sb.AppendLine("#if defined(__GNUC__) || defined(__clang__)");
        sb.AppendLine("#define HMI_WEAK __attribute__((weak))");
        sb.AppendLine("#else");
        sb.AppendLine("#define HMI_WEAK");
        sb.AppendLine("#endif");
        sb.AppendLine("#endif");
        sb.AppendLine();

        sb.AppendLine("typedef void (*hmi_script_fn)(void);");
        sb.AppendLine();
        sb.AppendLine("typedef struct {");
        sb.AppendLine("    const char* id;");
        sb.AppendLine("    hmi_script_fn fn;");
        sb.AppendLine("} script_entry_t;");
        sb.AppendLine();

        if (scripts.Count == 0)
        {
            sb.AppendLine("// No scripts.");
            sb.AppendLine("int hmi_run_script(const char* script_id) {");
            sb.AppendLine("    (void)script_id;");
            sb.AppendLine("    return -1;");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // 每个脚本的 weak stub 入口
        sb.AppendLine("/* 脚本入口 —— weak 实现，用户/固件可提供同名 strong 实现覆盖 */");
        foreach (var script in scripts)
        {
            var fnName = "script_" + RuntimeTagsCodeGen.SanitizeIdentifierPublic(script.Id);
            // 脚本名会进入块注释：先做 C 字符串转义，再消毒 "*/" 与换行，
            // 否则脚本名 "a*/int x;/*" 会提前结束注释并注入可执行代码。
            var label = SanitizeComment(script.Name.Length > 0 ? script.Name : script.Id);
            sb.AppendLine($"HMI_WEAK void {fnName}(void) {{ /* TODO: 脚本 '{label}' 逻辑待实现 */ }}");
        }
        sb.AppendLine();

        // 分发表
        sb.AppendLine("static const script_entry_t HMI_SCRIPTS[] = {");
        foreach (var script in scripts)
        {
            var fnName = "script_" + RuntimeTagsCodeGen.SanitizeIdentifierPublic(script.Id);
            var id = EscapeCString(script.Id);
            sb.AppendLine($"    {{\"{id}\", {fnName}}},");
        }
        sb.AppendLine("};");
        sb.AppendLine("static const int HMI_SCRIPT_COUNT = sizeof(HMI_SCRIPTS) / sizeof(HMI_SCRIPTS[0]);");
        sb.AppendLine();

        // 派发 API
        sb.AppendLine("/* 按 script_id 派发执行；未找到返回 -1 */");
        sb.AppendLine("int hmi_run_script(const char* script_id) {");
        sb.AppendLine("    if (script_id == NULL) return -1;");
        sb.AppendLine("    for (int i = 0; i < HMI_SCRIPT_COUNT; i++) {");
        sb.AppendLine("        if (strcmp(HMI_SCRIPTS[i].id, script_id) == 0) {");
        sb.AppendLine("            HMI_SCRIPTS[i].fn();");
        sb.AppendLine("            return 0;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("    return -1;");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>转义 C 字符串字面量中的特殊字符（反斜杠/引号/换行/制表符）。</summary>
    private static string EscapeCString(string s)
    {
        var sb = new StringBuilder(s.Length);
        foreach (var c in s)
        {
            switch (c)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default: sb.Append(c); break;
            }
        }
        return sb.ToString();
    }

    /// <summary>消毒注释文本：禁止 "*/" 提前结束块注释，禁止换行逃出注释行。</summary>
    private static string SanitizeComment(string s)
        => EscapeCString(s).Replace("*/", "* /").Replace("\r", " ").Replace("\n", " ");
}
