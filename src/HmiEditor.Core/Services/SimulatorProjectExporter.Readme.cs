/// <summary>SimulatorProjectExporter 分部 —— README.md 生成。</summary>
public static partial class SimulatorProjectExporter
{
    private static string BuildReadme(HmiProject project, IReadOnlyList<string> screenFunctions)
    {
        // 统一 LVGL 版本：分支名与依赖表跟随 project.LvglVersion，避免与 generated_hmi.c 头部不一致。
        var lvglVersion = project.LvglVersion;
        var lvglBranch = $"release/v{lvglVersion}";
        var sb = new StringBuilder();
        sb.AppendLine($"# HMI 模拟器工程 — {project.Name}");
        sb.AppendLine();
        sb.AppendLine("由 HMI Editor 自动生成。在 PC 上编译运行后, 可预览实际生成的 LVGL 画面, 完成「设计 → 生成 → 验证」闭环。");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine("## 支持矩阵");
        sb.AppendLine();
        sb.AppendLine("| 操作系统 | 版本 | 编译器 | 架构 |");
        sb.AppendLine("|---|---|---|---|");
        sb.AppendLine("| Windows | 10 / 11 | MSVC 2019+ / MinGW-w64 | x64 / ARM64 |");
        sb.AppendLine("| Linux | Ubuntu 20.04+ / 22.04+ / 24.04+ | GCC 9+ / Clang 12+ | x86_64 / ARM / ARM64 |");
        sb.AppendLine("| macOS | 12 (Monterey)+ | Apple Clang (Xcode) | x86_64 / arm64 (Apple Silicon) |");
        sb.AppendLine();
        sb.AppendLine("- **GPU**: 渲染采用 LVGL 软件光栅化 (`LV_USE_DRAW_SW`), 兼容任意 GPU / 集成显卡 / 无 GPU 环境; 开启硬件加速需自行集成对应后端。");
        sb.AppendLine("- **外设**: 鼠标(含滚轮) / 键盘; SDL 鼠标驱动同时处理触摸事件 (`lv_sdl_mouse_create()` + `lv_sdl_keyboard_create()`)。");
        sb.AppendLine();
        sb.AppendLine("## 依赖");
        sb.AppendLine();
        sb.AppendLine("| 依赖 | 版本 | 用途 |");
        sb.AppendLine("|---|---|---|");
        sb.AppendLine("| CMake | 3.16+ | 构建系统 |");
        sb.AppendLine("| SDL2 | 2.0.20+ (建议保持最新安全补丁) | 窗口 / 输入 / 渲染 |");
        sb.AppendLine($"| LVGL | v{lvglVersion} | UI 框架 (git clone --depth 1 --branch {lvglBranch}) |");
        sb.AppendLine();
        sb.AppendLine("### 各平台依赖安装");
        sb.AppendLine();
        sb.AppendLine("**Ubuntu / Debian**:");
        sb.AppendLine("```bash");
        sb.AppendLine("sudo apt update && sudo apt install -y cmake build-essential libsdl2-dev");
        sb.AppendLine($"git clone --depth 1 --branch {lvglBranch} https://github.com/lvgl/lvgl.git ../lvgl");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("**Windows (MSVC + vcpkg)**:");
        sb.AppendLine("```powershell");
        sb.AppendLine("git clone https://github.com/microsoft/vcpkg && cd vcpkg && .\\bootstrap-vcpkg.bat");
        sb.AppendLine(".\\vcpkg install sdl2:x64-windows");
        sb.AppendLine($"git clone --depth 1 --branch {lvglBranch} https://github.com/lvgl/lvgl.git ..\\lvgl");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("**Windows (MinGW64, MSYS2)**:");
        sb.AppendLine("```bash");
        sb.AppendLine("pacman -S --needed mingw-w64-x86_64-toolchain mingw-w64-x86_64-SDL2 cmake");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("**macOS (Homebrew)**:");
        sb.AppendLine("```bash");
        sb.AppendLine("brew install cmake sdl2");
        sb.AppendLine($"git clone --depth 1 --branch {lvglBranch} https://github.com/lvgl/lvgl.git ../lvgl");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("## 构建");
        sb.AppendLine();
        sb.AppendLine("```bash");
        sb.AppendLine("cmake -B build -DLVGL_DIR=../lvgl .");
        sb.AppendLine("cmake --build build");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("可选 CMake 变量:");
        sb.AppendLine("- `-DLVGL_DIR=<path>` — LVGL 源码目录 (默认 `../lvgl`)");
        sb.AppendLine("- `-DCMAKE_BUILD_TYPE=Release|Debug` — 默认 Release (`-O2`, 性能优先)");
        sb.AppendLine("- Windows (vcpkg): 追加 `-DCMAKE_TOOLCHAIN_FILE=<vcpkg>/scripts/buildsystems/vcpkg.cmake`");
        sb.AppendLine();
        sb.AppendLine("## 运行");
        sb.AppendLine();
        sb.AppendLine("```bash");
        sb.AppendLine("./build/hmi_sim                       # 按 sim_config.h 默认参数运行");
        sb.AppendLine("./build/hmi_sim --scale 2             # 2 倍窗口放大");
        sb.AppendLine("./build/hmi_sim --window 1280x800     # 模拟 1280x800 设备分辨率并铺满/适配");
        sb.AppendLine("./build/hmi_sim --fps 120             # 目标帧率 120fps");
        sb.AppendLine("./build/hmi_sim --selftest            # 自检: 渲染 300 帧后输出 PASS/FAIL");
        sb.AppendLine("./build/hmi_sim --help                # 查看全部参数");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("| 参数 | 说明 | 范围 |");
        sb.AppendLine("|---|---|---|");
        sb.AppendLine("| `--window <WxH>` | 设备分辨率/画布 (如 1280x800)，内容自动铺满/适配；0=设计分辨率 | - |");
        sb.AppendLine("| `--scale <n>` | 窗口放大倍数（不改画布，用 SDL zoom 等比放大窗口） | 1-4 |");
        sb.AppendLine("| `--fps <n>` | 目标帧率 (主循环节流) | 1-240 |");
        sb.AppendLine("| `--selftest` | 自检模式: 渲染后输出 PASS/FAIL 并以退出码 0/1 结束 | - |");
        sb.AppendLine("| `--help` / `-h` | 显示帮助 | - |");
        sb.AppendLine();
        sb.AppendLine("## 配置 (`sim_config.h`)");
        sb.AppendLine();
        sb.AppendLine("修改后重新编译生效; 命令行参数优先级更高。");
        sb.AppendLine();
        sb.AppendLine("| 宏 | 默认 | 说明 |");
        sb.AppendLine("|---|---|---|");
        sb.AppendLine("| `SIM_WINDOW_WIDTH / HEIGHT` | 屏幕分辨率 | 画布（display）逻辑分辨率 |");
        sb.AppendLine("| `SIM_WINDOW_TITLE` | HMI Simulator | 窗口标题 |");
        sb.AppendLine("| `SIM_TARGET_FPS` | 60 | 目标帧率 |");
        sb.AppendLine("| `SIM_SCALE` | 1 | 窗口放大倍数（SDL zoom，不改画布） |");
        sb.AppendLine("| `SIM_FIT_MODE` | 0 | `--window` 适配模式：0=Fill 拉伸铺满，1=Fit 等比居中 |");
        sb.AppendLine("| `SIM_SELFTEST_FRAMES` | 300 | 自检渲染帧数 |");
        sb.AppendLine();
        sb.AppendLine("性能相关配置见 `lv_conf.h` (`LV_MEM_SIZE` / `LV_DISP_DEF_REFR_PERIOD` / `LV_USE_PERF_MONITOR` / `LV_USE_MEM_MONITOR`)。");
        sb.AppendLine();
        sb.AppendLine("## 自动化测试");
        sb.AppendLine();
        sb.AppendLine("```bash");
        sb.AppendLine("ctest --test-dir build --output-on-failure");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine("- 内置 `simulator_selftest`: 以 `SDL_VIDEODRIVER=dummy` 无头模式渲染并校验显示/活动屏幕, 供 CI 使用。");
        sb.AppendLine("- 建议的验证协议: ① 构建通过 → ② `--selftest` PASS → ③ 人工预览各屏幕交互 → ④ 性能观察 (`LV_USE_PERF_MONITOR=1`)。");
        sb.AppendLine();
        sb.AppendLine("## 屏幕");
        sb.AppendLine();
        foreach (var fn in screenFunctions)
            sb.AppendLine($"- `{fn}` — 预创建, 启动后加载第一个");
        sb.AppendLine();
        sb.AppendLine("## 常见问题 (FAQ)");
        sb.AppendLine();
        sb.AppendLine("**Q: `pkg-config` 找不到 sdl2?**");
        sb.AppendLine("  确认已安装 `libsdl2-dev` (Linux) / `sdl2` (brew, macOS); Windows 请用 vcpkg 或 MSYS2 方式。");
        sb.AppendLine();
        sb.AppendLine("**Q: 触摸 / 鼠标点击无反应?**");
        sb.AppendLine("  确认 `main.c` 中 `lv_sdl_mouse_create()` / `lv_sdl_keyboard_create()` 已调用(默认已注册); SDL 鼠标驱动会处理触摸事件 (SDL_FINGER*)。");
        sb.AppendLine();
        sb.AppendLine("**Q: 中文显示为方块?**");
        sb.AppendLine("  需在 LVGL 中启用支持 CJK 的字体 (如 `NotoSansCJK`), 并将默认字体指向它 (`lv_conf.h` 或主题)。");
        sb.AppendLine();
        sb.AppendLine("**Q: 模拟器卡顿 / 帧率低?**");
        sb.AppendLine("  ① 检查 `--fps` 上限; ② `LV_USE_PERF_MONITOR=1` 观察实际 FPS 与内存; ③ 降低 `LV_COLOR_DEPTH` 至 16 或精简复杂控件; ④ 用 Release 构建 (`-O2`)。");
        sb.AppendLine();
        sb.AppendLine("**Q: 无头服务器 (CI) 上运行失败?**");
        sb.AppendLine("  已自动设置 `SDL_VIDEODRIVER=dummy`; 如仍失败, 确认 SDL2 已安装且版本 ≥ 2.0.20。");
        sb.AppendLine();
        sb.AppendLine("## 安全与更新");
        sb.AppendLine();
        sb.AppendLine("- 保持 SDL2 与 LVGL 为最新稳定版以获取安全补丁 (SDL2 安全公告: SDL 项目发布页)。");
        sb.AppendLine("- 生成代码 (main.c / generated_hmi.c / generated_security.h / generated_runtime.h) 由编辑器重导后覆盖, 自定义请写入 `sim_config.h` 或单独扩展源文件。");
        return sb.ToString();
    }
}
