using System.Text;
using HmiEditor.Core.Models;

namespace HmiEditor.Core.Services;

/// <summary>Modbus RTU 连接参数（从 DeviceConnection.Config 解析）。</summary>
public sealed record RtuParams(string Dev, int Baud, char Parity, int TmoMs, IReadOnlyList<int> SlaveIds);

/// <summary>Modbus TCP 连接参数（从 DeviceConnection.Config 解析）。</summary>
public sealed record TcpParams(string Host, int Port, int TmoMs, IReadOnlyList<int> SlaveIds);

/// <summary>MQTT 连接参数（从 DeviceConnection.Config 解析）。</summary>
public sealed record MqttParams(string Host, int Port, string ClientId, string User, string Pass, int KeepAlive,
    // ── TLS（阶段 282；契约见 MqttTlsContract）—— 全可空：老工程不带这些键 ⇒ ini 里不出现 ⇒ 设备侧按 off 处理 ──
    string? Tls = null, string? TlsPskId = null, string? TlsPskFile = null, string? TlsCaPath = null,
    string? TlsLocalPort = null);

/// <summary>
/// 生成设备端通讯配置 —— 两个产物共用同一份参数解析：
///   <list type="bullet">
///     <item><c>Generate()</c>：C 宏头文件 generated_comm.h（编译期，固件 comm_core.c 经
///       <c>__has_include</c> 优先引用，缺省回退 runtime_config.h 硬编码宏）；</item>
///     <item><c>GenerateRuntimeConfigText()</c>：运行时 INI 文本（IDE 下载时下发到设备
///       <c>/mnt/UDISK/hmi/comm_config.ini</c>，宿主 comm_core 启动读取，覆盖编译期默认 ——
///       改连接参数无需重编固件）。</item>
///   </list>
/// COM 号按约定映射为 <c>/dev/ttyS&lt;N&gt;</c>（COM1→/dev/ttyS1 … COM6→/dev/ttyS6），
/// RS485 即 UART3 = /dev/ttyS3。固件为单通道架构（单 RTU + 单 TCP + 单 MQTT），
/// 同名协议取第一条启用的连接。
/// </summary>
public static class CommConfigCodeGen
{
    // ── 参数解析（C 宏生成与运行时 INI 生成共用） ──

    /// <summary>解析 Modbus RTU 参数；连接为 null 或协议不符返回 null。</summary>
    public static RtuParams? ResolveRtu(DeviceConnection? c)
    {
        if (c is not { IsEnabled: true } || c.DriverId != "modbus-rtu") return null;
        var cfg = c.Config ?? new Dictionary<string, string>();
        var dev = MapComToTty(Get(cfg, "port", "COM1"));
        var baud = ParseInt(Get(cfg, "baud", "9600"), 9600);
        var parity = Get(cfg, "parity", "None") switch
        {
            "Even" => 'E',
            "Odd" => 'O',
            _ => 'N',
        };
        var tmo = ParseInt(Get(cfg, "timeoutMs", "300"), 300);
        return new RtuParams(dev, baud, parity, tmo, ResolveSlaveIds(c));
    }

    /// <summary>解析 Modbus TCP 参数；连接为 null 或协议不符返回 null。</summary>
    public static TcpParams? ResolveTcp(DeviceConnection? c)
    {
        if (c is not { IsEnabled: true } || c.DriverId != "modbus-tcp") return null;
        var cfg = c.Config ?? new Dictionary<string, string>();
        var host = Get(cfg, "host", "192.168.1.1");
        var port = ParseInt(Get(cfg, "port", "502"), 502);
        var tmo = ParseInt(Get(cfg, "timeoutMs", "3000"), 3000);
        return new TcpParams(host, port, tmo, ResolveSlaveIds(c));
    }

    /// <summary>解析 MQTT 参数；连接为 null 或协议不符返回 null。</summary>
    public static MqttParams? ResolveMqtt(DeviceConnection? c)
    {
        if (c is not { IsEnabled: true } || c.DriverId != "mqtt") return null;
        var cfg = c.Config ?? new Dictionary<string, string>();
        var host = Get(cfg, "broker", "localhost");
        var port = ParseInt(Get(cfg, "port", "1883"), 1883);
        var client = Get(cfg, "clientId", "hmi-t113");
        var user = Get(cfg, "username", "");
        var pass = Get(cfg, "password", "");
        var keep = ParseInt(Get(cfg, "keepAlive", "60"), 60);
        // TLS 四键**可缺省**：缺省 ⇒ 一个都不发（设备侧 `mqtt.tls` 缺省为 off ⇒ 向后兼容）
        // ⚠ 键名分两层：**连接参数**是短名（tls / tlsPskId / tlsPskFile / tlsCaPath，与 broker/port 同层），
        //   落到 ini 才是 mqtt.tls.*（阶段 282 这里曾把 ini 键名当成参数名读 —— 见 §199.3）
        var tls = Get(cfg, "tls", "");
        var pskId = Get(cfg, "tlsPskId", "");
        var pskFile = Get(cfg, "tlsPskFile", "");
        var caPath = Get(cfg, "tlsCaPath", "");
        var localPort = Get(cfg, MqttTlsContract.LocalPortKey, "");
        return new MqttParams(host, port, client, user, pass, keep, tls, pskId, pskFile, caPath, localPort);
    }

    /// <summary>从站列表：子设备（启用）站号排序去重；无子设备回退连接参数 slaveId。</summary>
    private static IReadOnlyList<int> ResolveSlaveIds(DeviceConnection c)
    {
        var cfg = c.Config ?? new Dictionary<string, string>();
        var slaves = c.Slaves is { Count: > 0 }
            ? c.Slaves.Where(s => s.IsEnabled).Select(s => s.SlaveAddress).Distinct().OrderBy(x => x).ToList()
            : new List<int> { ParseInt(Get(cfg, "slaveId", "1"), 1) };
        return slaves.Count > 0 ? slaves : new List<int> { 1 };
    }

    /// <summary>生成 generated_comm.h 内容（无连接时返回空头文件）。</summary>
    public static string Generate(IReadOnlyList<DeviceConnection>? connections)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by HmiEditor — device communication config. DO NOT EDIT.");
        sb.AppendLine("#ifndef HMI_GENERATED_COMM_H");
        sb.AppendLine("#define HMI_GENERATED_COMM_H");
        sb.AppendLine();

        foreach (var c in connections ?? new List<DeviceConnection>())
        {
            if (ResolveRtu(c) is { } rtu) AppendModbusRtu(sb, rtu);
            else if (ResolveTcp(c) is { } tcp) AppendModbusTcp(sb, tcp);
            else if (ResolveMqtt(c) is { } mqtt) AppendMqtt(sb, mqtt);
        }

        sb.AppendLine("#endif /* HMI_GENERATED_COMM_H */");
        return sb.ToString();
    }

    /// <summary>
    /// 生成运行时连接配置文本（INI 风格 key=value，固件 comm_core.c 启动读取，
    /// 部署到 <c>/mnt/UDISK/hmi/comm_config.ini</c>）。固件单通道架构：同名协议取第一条
    /// 启用连接。空连接返回空字符串（不写文件，固件回退编译期默认）。
    /// </summary>
    public static string GenerateRuntimeConfigText(IReadOnlyList<DeviceConnection>? connections)
    {
        var conns = connections ?? new List<DeviceConnection>();
        RtuParams? rtu = null;
        TcpParams? tcp = null;
        MqttParams? mqtt = null;
        foreach (var c in conns)
        {
            rtu ??= ResolveRtu(c);
            tcp ??= ResolveTcp(c);
            mqtt ??= ResolveMqtt(c);
            if (rtu != null && tcp != null && mqtt != null) break;
        }
        if (rtu == null && tcp == null && mqtt == null) return "";

        var sb = new StringBuilder();
        sb.AppendLine("# zhishu-HMI runtime communication config (comm_core.c reads at startup)");
        if (rtu != null)
        {
            sb.AppendLine($"rtu.dev={Plain(rtu.Dev)}");
            sb.AppendLine($"rtu.baud={rtu.Baud}");
            sb.AppendLine($"rtu.parity={rtu.Parity}");
            sb.AppendLine($"rtu.tmo_ms={rtu.TmoMs}");
        }
        if (tcp != null)
        {
            sb.AppendLine($"tcp.host={Plain(tcp.Host)}");
            sb.AppendLine($"tcp.port={tcp.Port}");
            sb.AppendLine($"tcp.tmo_ms={tcp.TmoMs}");
        }
        if (mqtt != null)
        {
            // ── 端点决定（阶段 284）：TLS 开着 ⇒ 客户端连**本机代理**，broker 地址只作为**代理的上游** ──
            //    ⚠ 这条是"不许绕过代理"在生成期的落点：TLS 开着时 `mqtt.host` **绝不**写成 broker 地址
            var tlsModeOk = MqttTlsContract.TryParseMode(mqtt.Tls ?? "", out var tlsMode);
            var tlsOn = tlsModeOk && tlsMode != MqttTlsMode.Off;
            var clientHost = mqtt.Host;
            var clientPort = mqtt.Port;
            if (tlsOn)
            {
                MqttTlsContract.TryParsePort(mqtt.TlsLocalPort, MqttTlsContract.DefaultLocalPort, out var localPort);
                clientHost = MqttTlsContract.Localhost;
                clientPort = localPort;
            }

            sb.AppendLine($"mqtt.host={Plain(clientHost)}");
            sb.AppendLine($"mqtt.port={clientPort}");
            sb.AppendLine($"mqtt.client_id={Plain(mqtt.ClientId)}");
            sb.AppendLine($"mqtt.username={Plain(mqtt.User)}");
            sb.AppendLine($"mqtt.password={Plain(mqtt.Pass)}");
            sb.AppendLine($"mqtt.keepalive={mqtt.KeepAlive}");
            // TLS（阶段 282）：**只有配了模式才发** —— 老工程 ini 逐字节不变（向后兼容）；
            // 取值为空的可选项不发（设备侧按"该模式缺必需项"拒绝启动，红线：不降级）
            if (!string.IsNullOrEmpty(mqtt.Tls))
            {
                sb.AppendLine($"{MqttTlsContract.ModeKey}={Plain(mqtt.Tls!)}");
                if (!string.IsNullOrEmpty(mqtt.TlsPskId)) sb.AppendLine($"{MqttTlsContract.PskIdKey}={Plain(mqtt.TlsPskId!)}");
                if (!string.IsNullOrEmpty(mqtt.TlsPskFile)) sb.AppendLine($"{MqttTlsContract.PskFileKey}={Plain(mqtt.TlsPskFile!)}");
                if (!string.IsNullOrEmpty(mqtt.TlsCaPath)) sb.AppendLine($"{MqttTlsContract.CaPathKey}={Plain(mqtt.TlsCaPath!)}");

                // 下面三个只有**TLS 真开着**才发：`tls=off` 时没有代理，发 upstream 只会误导
                // （非法模式同理不发 —— 设备启动时按"未知模式"拒绝，红线：不降级）
                if (tlsOn)
                {
                    if (!string.IsNullOrEmpty(mqtt.TlsLocalPort)) sb.AppendLine($"{MqttTlsContract.LocalPortKey}={Plain(mqtt.TlsLocalPort!)}");
                    // 代理的上游（= 真正的 broker）—— **只给代理读**，MQTT 客户端读的是上面的 loopback
                    sb.AppendLine($"mqtt.tls.upstream_host={Plain(mqtt.Host)}");
                    sb.AppendLine($"mqtt.tls.upstream_port={mqtt.Port}");
                }
            }
        }
        return sb.ToString();
    }

    // ── C 宏输出（generated_comm.h） ──

    private static void AppendModbusRtu(StringBuilder sb, RtuParams rtu)
    {
        var slaveList = string.Join(", ", rtu.SlaveIds);
        sb.AppendLine("/* Modbus RTU (RS485) — 设备端 mb_rtu_init(dev, baud, parity, tmo) */");
        sb.AppendLine($"#define HMI_COMM_RTU_DEV   \"{CString(rtu.Dev)}\"");
        sb.AppendLine($"#define HMI_COMM_RTU_BAUD  {rtu.Baud}");
        sb.AppendLine($"#define HMI_COMM_RTU_PARITY '{rtu.Parity}'");
        sb.AppendLine($"#define HMI_COMM_RTU_TMO_MS {rtu.TmoMs}");
        sb.AppendLine($"#define HMI_COMM_RTU_SLAVES \"{slaveList}\"");
        sb.AppendLine();
    }

    private static void AppendModbusTcp(StringBuilder sb, TcpParams tcp)
    {
        var slaveList = string.Join(", ", tcp.SlaveIds);
        sb.AppendLine("/* Modbus TCP (eth0:502) — 设备端 mb_tcp_init(host, port, tmo) */");
        sb.AppendLine($"#define HMI_COMM_TCP_HOST   \"{CString(tcp.Host)}\"");
        sb.AppendLine($"#define HMI_COMM_TCP_PORT   {tcp.Port}");
        sb.AppendLine($"#define HMI_COMM_TCP_TMO_MS {tcp.TmoMs}");
        sb.AppendLine($"#define HMI_COMM_TCP_SLAVES \"{slaveList}\"");
        sb.AppendLine();
    }

    private static void AppendMqtt(StringBuilder sb, MqttParams mqtt)
    {
        sb.AppendLine("/* MQTT — 设备端 mqtt_start(host, port, client, user, pass, keepalive) */");
        sb.AppendLine($"#define HMI_COMM_MQTT_HOST       \"{CString(mqtt.Host)}\"");
        sb.AppendLine($"#define HMI_COMM_MQTT_PORT       {mqtt.Port}");
        sb.AppendLine($"#define HMI_COMM_MQTT_CLIENT_ID  \"{CString(mqtt.ClientId)}\"");
        sb.AppendLine($"#define HMI_COMM_MQTT_USER       \"{CString(mqtt.User)}\"");
        sb.AppendLine($"#define HMI_COMM_MQTT_PASS       \"{CString(mqtt.Pass)}\"");
        sb.AppendLine($"#define HMI_COMM_MQTT_KEEPALIVE  {mqtt.KeepAlive}");
        sb.AppendLine();
    }

    /// <summary>COM1~COM6 → /dev/ttyS1~/dev/ttyS6；其余输入原样返回（如 /dev/ttyUSB0）。</summary>
    private static string MapComToTty(string port)
    {
        if (!string.IsNullOrWhiteSpace(port)
            && port.StartsWith("COM", StringComparison.OrdinalIgnoreCase)
            && int.TryParse(port[3..], out var n) && n >= 1)
        {
            return $"/dev/ttyS{n}";
        }
        return port;
    }

    /// <summary>INI 值净化：去除换行/回车/行首空格（防注入额外键值行）。</summary>
    private static string Plain(string s) =>
        (s ?? "").Replace("\r", " ").Replace("\n", " ").Trim();

    private static string Get(IReadOnlyDictionary<string, string> cfg, string key, string fallback) =>
        cfg.TryGetValue(key, out var v) && !string.IsNullOrWhiteSpace(v) ? v : fallback;

    private static int ParseInt(string s, int fallback) =>
        int.TryParse(s, out var n) ? n : fallback;

    /// <summary>C 字符串转义（引号/反斜杠/控制字符）。</summary>
    private static string CString(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r");
}
